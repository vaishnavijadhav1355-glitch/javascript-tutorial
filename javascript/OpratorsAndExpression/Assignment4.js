let x = 10;

console.log("Initial value:", x);

x += 5;   // Add 5
console.log("After x += 5:", x);

x *= 3;   // Multiply by 3
console.log("After x *= 3:", x);

x -= 10;  // Subtract 10
console.log("After x -= 10:", x);

x /= 2;   // Divide by 2
console.log("After x /= 2:", x);

x %= 3;   // Modulus with 3
console.log("After x %= 3:", x);